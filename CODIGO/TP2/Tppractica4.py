#4 programa que calcula el perimetro de
#un triangulo tomando como valores los lados del mismo
print("EL siguiente programa calcula el perimetro de un triangulo")
print()
lado1 = float(input("Ingrese el valor del primer lado: "))
lado2 = float(input("Ingrese el valor del segundo lado: "))
lado3 = float(input("Ingrese el valor del tercer lado: "))

perimetro = (lado1 + lado2 + lado3)

print(f"El Perimetro es igual a: {perimetro}")

